// Regenerates src/tools/date-calculator/taiwan-holidays.data.ts from the official Taiwan government
// office calendar (中華民國政府行政機關辦公日曆表, https://data.gov.tw/dataset/14718), as cleaned up
// by https://github.com/ruyut/TaiwanCalendar.
//
// Usage:
//   node scripts/update-taiwan-holidays.mjs 2017 2028               # download from the jsDelivr CDN
//   node scripts/update-taiwan-holidays.mjs 2017 2028 --from <dir>  # read <dir>/<year>.json instead
//
// The government publishes the next year's calendar around June; run this once it is out.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const currentDirname = dirname(fileURLToPath(import.meta.url));
const outputFile = join(currentDirname, '..', 'src', 'tools', 'date-calculator', 'taiwan-holidays.data.ts');

const [firstArg, lastArg, ...rest] = process.argv.slice(2);
const first = Number(firstArg);
const last = Number(lastArg);
const fromIndex = rest.indexOf('--from');
const fromDir = fromIndex >= 0 ? rest[fromIndex + 1] : undefined;

if (!Number.isInteger(first) || !Number.isInteger(last) || first > last) {
  console.error('Usage: node scripts/update-taiwan-holidays.mjs <firstYear> <lastYear> [--from <dir>]');
  process.exit(1);
}

async function loadYear(year) {
  if (fromDir) {
    return JSON.parse(await readFile(join(fromDir, `${year}.json`), 'utf-8'));
  }

  const response = await fetch(`https://cdn.jsdelivr.net/gh/ruyut/TaiwanCalendar/data/${year}.json`);
  if (!response.ok) {
    throw new Error(`No calendar for ${year} (HTTP ${response.status})`);
  }
  return response.json();
}

function toIsoDate(compact) {
  if (!/^\d{8}$/.test(compact)) {
    throw new Error(`Unexpected date "${compact}"`);
  }
  return `${compact.slice(0, 4)}-${compact.slice(4, 6)}-${compact.slice(6, 8)}`;
}

const holidays = [];
const makeupWorkdays = [];

for (let year = first; year <= last; year++) {
  const days = await loadYear(year);
  const isLeap = (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;

  // Refuse partial or malformed data rather than silently miscounting
  if (!Array.isArray(days) || days.length !== (isLeap ? 366 : 365)) {
    throw new Error(`${year}: expected a full year of entries, got ${days?.length}`);
  }

  for (const { date, isHoliday, description } of days) {
    const iso = toIsoDate(date);
    const weekday = new Date(`${iso}T00:00:00Z`).getUTCDay();
    const isWeekend = weekday === 0 || weekday === 6;
    const name = String(description ?? '').trim();

    // Named days off: national holidays, bridge days and substitute days off (補假)
    if (isHoliday && name) {
      holidays.push([iso, name]);
    }
    // Saturdays or Sundays that are working days to make up for a bridge holiday (補行上班)
    if (!isHoliday && isWeekend) {
      makeupWorkdays.push(iso);
    }
  }
}

const content = `// Generated by scripts/update-taiwan-holidays.mjs, do not edit by hand.
// Source: 中華民國政府行政機關辦公日曆表 (https://data.gov.tw/dataset/14718), published by the
// Directorate-General of Personnel Administration, via https://github.com/ruyut/TaiwanCalendar.

export const taiwanHolidayYears = { first: ${first}, last: ${last} };

// Named days off, including substitute days off (補假)
export const taiwanHolidays: Record<string, string> = {
${holidays.map(([date, name]) => `  '${date}': '${name.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}',`).join('\n')}
};

// Weekend days that are working days (補行上班 / 調整上班)
export const taiwanMakeupWorkdays: string[] = [
${makeupWorkdays.map(date => `  '${date}',`).join('\n')}
];
`;

await writeFile(outputFile, content);
console.log(`Wrote ${holidays.length} holidays and ${makeupWorkdays.length} makeup workdays (${first}-${last}) to ${outputFile}`);
